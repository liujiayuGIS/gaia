// Run scripts/qa_quality_server.py first; uses an isolated public-data workspace.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs');const assert=require('node:assert/strict');
const base=process.env.BASE_URL||'http://127.0.0.1:8767';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try{
  fs.mkdirSync('outputs/spatial-quality',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(45000);
  const layers=await (await page.request.get(base+'/api/layers')).json();
  const vector=layers.find(x=>x.kind!=='raster'),raster=layers.find(x=>x.kind==='raster');
  assert(vector&&raster);
  await page.goto(base);await page.waitForSelector('.map-canvas[data-ready="true"]');
  await page.locator('[data-layer-id="'+raster.id+'"] .layer-symbol').click();
  await page.getByText('数据含义与时间',{exact:true}).click();
  await page.getByLabel('数量含义',{exact:true}).selectOption('elevation');
  await page.getByLabel('数据单位',{exact:true}).fill('m');
  await page.getByLabel('语义来源',{exact:true}).fill('USGS 3DEP service metadata');
  await page.getByLabel('语义确认依据',{exact:true}).fill('Public sample elevation values are in metres; QA declaration.');
  await page.getByRole('button',{name:'保存数据说明',exact:true}).click();
  await page.waitForResponse(r=>r.url().endsWith('/api/layers')&&r.status()===200);
  const updated=await (await page.request.get(base+'/api/layers')).json();
  assert.equal(updated.find(x=>x.id===raster.id).semantics.unit,'m');
  await page.getByRole('button',{name:'数据面板',exact:true}).click();
  await page.locator('[data-layer-id="'+vector.id+'"] .tree-name').click();
  await page.getByRole('button',{name:'工具面板',exact:true}).click();
  await page.getByLabel('检索算法').fill('native:buffer');
  await page.locator('.tool-catalog button').first().click();
  await page.getByRole('button',{name:'预检查',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'经纬度当米'}).waitFor();
  assert.equal((await (await page.request.get(base+'/api/layers')).json()).length,layers.length);
  await page.screenshot({path:'outputs/spatial-quality/preflight.png'});
  await page.getByRole('button',{name:'检查出图',exact:true}).click();
  await page.getByRole('button',{name:'应用出版版式',exact:true}).click();
  await page.getByRole('button',{name:'检查当前布局',exact:true}).click();
  await page.getByAltText('本次审阅的完整地图布局').waitFor();
  await page.locator('.quality-pane .quality-details summary').click();
  await page.screenshot({path:'outputs/spatial-quality/desktop.png'});
  const layout=await (await page.request.get(base+'/api/layout')).json();
  assert.equal(layout.legend_position,'outside-right');assert.equal(layout.items.source.font_size,8);
  const exported=await page.request.post(base+'/api/layout/export',{data:{format:'pdf',dpi:300},timeout:120000});
  assert.equal(exported.status(),200,await exported.text());
  const result=await exported.json();assert(result.map_review_id);
  const review=await (await page.request.get(base+'/api/map-reviews/'+result.map_review_id)).json();
  assert(review.evidence.labeling_available);
  fs.writeFileSync('outputs/spatial-quality/rainier-quality.json',JSON.stringify(review,null,2));
  fs.writeFileSync('outputs/spatial-quality/rainier-map.pdf',await (await page.request.get(base+result.url)).body());
  fs.writeFileSync('outputs/spatial-quality/rainier-map.png',await (await page.request.get(base+result.preview_url)).body());
  await page.getByRole('button',{name:'外观设置',exact:true}).click();
  await page.getByRole('button',{name:'深色',exact:true}).click();
  await page.getByRole('button',{name:'检查出图',exact:true}).click();
  await page.screenshot({path:'outputs/spatial-quality/dark.png'});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'数据与工具',exact:true}).click();
  await page.screenshot({path:'outputs/spatial-quality/mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({browser:'passed',map_program_passed:review.report.passed,warnings:review.report.warnings,unverified:review.report.unverified}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
